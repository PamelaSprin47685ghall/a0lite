#!/usr/bin/env bash
# Install the system units that keep Agent Zero running across reboots.
#
# The units themselves contain no user names, UIDs or home paths. This script
# writes a drop-in per unit (agent-zero.service.d/10-user.conf) with User=,
# Group=, the home directory, the runtime directory and the user-manager
# dependency. The units assert that the drop-in exists, so a half-installed
# copy fails closed instead of running as root.
#
# Usage: sudo scripts/install-services.sh [user]
#
# A0_STAGE_ROOT=/tmp/stage scripts/install-services.sh [user] renders and
# installs everything under that root without touching /etc or systemd.
#
# Requires: systemd, a per-user Flatpak installation of
# org.agentzero.AgentZero, curl, and A0_AUTH_KEY already set through
# `flatpak override --user --env=A0_AUTH_KEY=...`.

set -euo pipefail

die() {
    printf 'install-services: %s\n' "$*" >&2
    exit 1
}

if [ "$#" -gt 1 ]; then
    die "usage: install-services.sh [user]"
fi

USER_NAME=${1:-${SUDO_USER:-}}
[ -n "$USER_NAME" ] || die "usage: install-services.sh [user] (or run through sudo)"

STAGE=${A0_STAGE_ROOT:-}
if [ -n "$STAGE" ]; then
    [ "$STAGE" != "/" ] || die "A0_STAGE_ROOT must not be /"
elif [ "$(id -u)" -ne 0 ]; then
    die "run as root, or set A0_STAGE_ROOT to stage the files"
fi

PASSWD_LINE=$(getent passwd "$USER_NAME") || die "no such user: $USER_NAME"
UID_N=$(id -u -- "$USER_NAME") || die "cannot resolve UID for: $USER_NAME"
GROUP_NAME=$(id -gn -- "$USER_NAME") || die "cannot resolve primary group for: $USER_NAME"
HOME_DIR=$(printf '%s\n' "$PASSWD_LINE" | cut -d: -f6)

[ "$UID_N" -ne 0 ] || die "refusing to install a root service; pass the desktop user"
case "$UID_N" in *[!0-9]*) die "bad UID for $USER_NAME: $UID_N" ;; esac
case "$USER_NAME" in -*) die "unsupported user name: $USER_NAME" ;; esac
case "$USER_NAME" in *[!A-Za-z0-9._@-]*) die "unsupported user name: $USER_NAME" ;; esac
case "$GROUP_NAME" in *[!A-Za-z0-9._@-]*) die "unsupported group name: $GROUP_NAME" ;; esac
case "$HOME_DIR" in
    /*) ;;
    *) die "home directory is not absolute: $HOME_DIR" ;;
esac
case "$HOME_DIR" in
    *[[:space:]]*|*\"*|*\'*|*\\*|*%*)
        die "unsupported character in home directory: $HOME_DIR"
        ;;
esac
[ -d "$HOME_DIR" ] || die "home directory does not exist: $HOME_DIR"

HERE=$(cd -- "$(dirname -- "$0")/.." && pwd)
[ -f "$HERE/systemd/agent-zero.service" ] || die "unit files are missing under $HERE/systemd"

if [ -n "$STAGE" ]; then
    UNIT_DIR=$STAGE/etc/systemd/system
    BIN_DIR=$STAGE/usr/local/bin
else
    UNIT_DIR=/etc/systemd/system
    BIN_DIR=/usr/local/bin
    for cmd in systemctl loginctl systemd-analyze curl install; do
        command -v "$cmd" >/dev/null 2>&1 || die "required command not found: $cmd"
    done
    [ -x /usr/bin/flatpak ] || die "/usr/bin/flatpak is missing"
fi

# Pull the display manager into the multi-user transaction when one exists, so
# a graphical boot shadows the real X server. A headless install has no such
# alias and must not depend on it.
DM_PRESENT=0
if [ -n "$STAGE" ]; then
    if [ -e "$STAGE/etc/systemd/system/display-manager.service" ] ||
       [ -L "$STAGE/etc/systemd/system/display-manager.service" ]; then
        DM_PRESENT=1
    fi
elif [ -e /etc/systemd/system/display-manager.service ] ||
     [ -e /usr/lib/systemd/system/display-manager.service ]; then
    DM_PRESENT=1
fi

WORK=$(mktemp -d "${TMPDIR:-/tmp}/a0-units.XXXXXX")
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/units/agent-zero.service.d" "$WORK/units/agent-zero-desktop.service.d"

write_dropin() {
    unit=$1
    out=$2
    {
        printf '# Generated by scripts/install-services.sh for user %s. Do not edit.\n' "$USER_NAME"
        printf '[Unit]\n'
        printf 'RequiresMountsFor=%s\n' "$HOME_DIR"
        printf 'After=user@%s.service\n' "$UID_N"
        printf 'Wants=user@%s.service\n' "$UID_N"
        if [ "$unit" = "agent-zero-desktop.service" ] && [ "$DM_PRESENT" = 1 ]; then
            printf 'Wants=display-manager.service\n'
        fi
        printf '\n[Service]\n'
        printf 'User=%s\n' "$USER_NAME"
        printf 'Group=%s\n' "$GROUP_NAME"
        printf 'Environment=XDG_RUNTIME_DIR=/run/user/%s\n' "$UID_N"
        printf 'Environment=DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/%s/bus\n' "$UID_N"
        printf 'Environment=XAUTHORITY=%s/.Xauthority\n' "$HOME_DIR"
        if [ "$unit" = "agent-zero.service" ]; then
            printf 'WorkingDirectory=%s\n' "$HOME_DIR"
        fi
    } > "$out"
}

cp "$HERE/systemd/agent-zero.service" "$WORK/units/agent-zero.service"
cp "$HERE/systemd/agent-zero-desktop.service" "$WORK/units/agent-zero-desktop.service"
write_dropin agent-zero.service "$WORK/units/agent-zero.service.d/10-user.conf"
write_dropin agent-zero-desktop.service "$WORK/units/agent-zero-desktop.service.d/10-user.conf"

install -Dm755 "$HERE/systemd/a0-desktop-start" "$BIN_DIR/a0-desktop-start"

if [ -z "$STAGE" ]; then
    # Load the staged units plus their drop-ins by name. The helper is already
    # at its final path, so this checks the same files systemd will read.
    SYSTEMD_UNIT_PATH="$WORK/units:" systemd-analyze verify \
        agent-zero.service agent-zero-desktop.service
    loginctl enable-linger "$USER_NAME"
fi

place() {
    src=$1
    dst=$2
    tmp="$dst.tmp.$$"
    install -Dm644 "$src" "$tmp"
    mv -f "$tmp" "$dst"
}

# Drop-ins first: if the last copy is interrupted, the unit files still assert
# their drop-in and fail closed instead of running as root.
place "$WORK/units/agent-zero.service.d/10-user.conf" \
    "$UNIT_DIR/agent-zero.service.d/10-user.conf"
place "$WORK/units/agent-zero-desktop.service.d/10-user.conf" \
    "$UNIT_DIR/agent-zero-desktop.service.d/10-user.conf"
place "$WORK/units/agent-zero.service" "$UNIT_DIR/agent-zero.service"
place "$WORK/units/agent-zero-desktop.service" "$UNIT_DIR/agent-zero-desktop.service"

if [ -n "$STAGE" ]; then
    printf 'staged under %s; systemd was not touched\n' "$STAGE"
    exit 0
fi

systemctl daemon-reload
systemctl reenable agent-zero.service agent-zero-desktop.service
systemctl restart agent-zero.service
systemctl restart agent-zero-desktop.service

if ! systemctl is-active --quiet agent-zero.service; then
    die "agent-zero.service is not active after restart"
fi
if ! systemctl is-active --quiet agent-zero-desktop.service; then
    die "agent-zero-desktop.service is not active after restart"
fi

A0_PORT=${A0_PORT:-5080}
printf 'waiting for the UI\n'
CODE=""
for _ in $(seq 1 60); do
    CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "http://127.0.0.1:$A0_PORT/api/health" || true)
    if [ "$CODE" = 200 ]; then
        break
    fi
    sleep 2
done
if [ "$CODE" != 200 ]; then
    printf 'install-services: UI health is %s after 120s\n' "${CODE:-000}" >&2
    printf 'install-services: journalctl -u agent-zero -n 40 --no-pager\n' >&2
    exit 1
fi
printf 'UI health %s\n' "$CODE"
